#!/usr/bin/env node
// Refreshes data/packs.js with new trivia questions.
//
//   node scripts/update-questions.mjs                 # Open Trivia DB only (free, no key)
//   node scripts/update-questions.mjs --claude        # also ask Claude for current-events questions
//   node scripts/update-questions.mjs --claude-only   # skip Open Trivia DB
//   node scripts/update-questions.mjs --import new.json   # add questions from a file, no network
//
// --import takes a JSON array of {category, difficulty, question, answer, wrong_answers, note}
// (the same shape Claude submits) and skips the online sources.
//
// --claude needs ANTHROPIC_API_KEY and `npm install` (for @anthropic-ai/sdk).
// Every question is validated and de-duplicated against the core bank and earlier packs
// before it's written, so a bad batch can't break the app.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import vm from "node:vm";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CORE_FILE = path.join(ROOT, "questions.js");
const PACK_FILE = path.join(ROOT, "data", "packs.js");

export const CATEGORY_IDS = ["pop", "music", "history", "geo", "sci", "sports", "random"];
const MAX_PACK_SIZE = 1500; // oldest pack questions drop off past this

// Open Trivia DB category number -> our category
export const OPENTDB_CATEGORIES = {
  9: "random", // General Knowledge
  11: "pop", // Film
  12: "music",
  14: "pop", // Television
  17: "sci", // Science & Nature
  21: "sports",
  22: "geo",
  23: "history",
  27: "sci", // Animals
};
const DIFFICULTY = { easy: 1, medium: 2, hard: 3 };

// ---------- helpers ----------
export const normalize = (s) =>
  String(s).toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, " ").trim();

// Short stable id from the question text, so pack order never matters.
export function idFor(q) {
  let h = 2166136261;
  for (const ch of normalize(q)) {
    h ^= ch.charCodeAt(0);
    h = Math.imul(h, 16777619);
  }
  return "p-" + (h >>> 0).toString(36);
}

export function validate(q) {
  const problems = [];
  if (!CATEGORY_IDS.includes(q.c)) problems.push(`unknown category "${q.c}"`);
  if (![1, 2, 3].includes(q.d)) problems.push("difficulty must be 1, 2 or 3");
  if (typeof q.q !== "string" || q.q.length < 10 || q.q.length > 300) problems.push("question length");
  if (typeof q.a !== "string" || !q.a.trim() || q.a.length > 120) problems.push("answer");
  if (!Array.isArray(q.w) || q.w.length !== 3) problems.push("needs exactly three wrong answers");
  else {
    const all = [q.a, ...q.w].map(normalize);
    if (new Set(all).size !== 4) problems.push("answers must all be different");
    if (q.w.some((w) => typeof w !== "string" || !w.trim() || w.length > 120)) problems.push("wrong answer text");
  }
  if (q.n != null && (typeof q.n !== "string" || q.n.length > 300)) problems.push("note too long");
  return problems;
}

// Open Trivia DB returns RFC 3986-encoded strings when asked with encode=url3986.
export function fromOpenTdb(result, catNumber, added) {
  const dec = (s) => decodeURIComponent(s).trim();
  const q = dec(result.question);
  return {
    id: idFor(q),
    c: OPENTDB_CATEGORIES[catNumber],
    d: DIFFICULTY[dec(result.difficulty)] || 2,
    q,
    a: dec(result.correct_answer),
    w: result.incorrect_answers.map(dec),
    n: "",
    src: "opentdb",
    added,
  };
}

// Adds new questions that pass validation and aren't duplicates. Returns { pack, accepted, rejected }.
export function mergeIntoPack(existingPack, candidates, coreQuestions) {
  const seen = new Set([...coreQuestions, ...existingPack].map((q) => normalize(q.q)));
  const accepted = [];
  const rejected = [];
  for (const cand of candidates) {
    const problems = validate(cand);
    const key = normalize(cand.q);
    if (seen.has(key)) problems.push("duplicate");
    if (problems.length) {
      rejected.push({ q: cand.q, problems });
      continue;
    }
    seen.add(key);
    accepted.push(cand);
  }
  const pack = [...existingPack, ...accepted].slice(-MAX_PACK_SIZE);
  return { pack, accepted, rejected };
}

// ---------- reading and writing the data files ----------
async function loadWindowVar(file, name) {
  try {
    const sandbox = { window: {} };
    vm.runInNewContext(await readFile(file, "utf8"), sandbox);
    return sandbox.window[name];
  } catch (e) {
    if (e.code === "ENOENT") return undefined;
    throw e;
  }
}

export function renderPackFile(questions, updated) {
  return (
    "// Generated by scripts/update-questions.mjs. Don't edit by hand; changes are overwritten.\n" +
    "// Open Trivia DB questions (src: \"opentdb\") are from https://opentdb.com, licensed CC BY-SA 4.0.\n" +
    "window.TRIVIA_PACKS = " +
    JSON.stringify({ updated, questions }, null, 1) +
    ";\n"
  );
}

// ---------- sources ----------
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchOpenTdb(added, perCategory = 10) {
  const out = [];
  for (const cat of Object.keys(OPENTDB_CATEGORIES)) {
    const url = `https://opentdb.com/api.php?amount=${perCategory}&category=${cat}&type=multiple&encode=url3986`;
    try {
      const res = await fetch(url);
      const body = await res.json();
      if (body.response_code === 0) out.push(...body.results.map((r) => fromOpenTdb(r, cat, added)));
      else console.warn(`Open Trivia DB category ${cat}: response_code ${body.response_code}`);
    } catch (e) {
      console.warn(`Open Trivia DB category ${cat} failed: ${e.message}`);
    }
    await sleep(5500); // the API allows one request every 5 seconds
  }
  return out;
}

const SUBMIT_TOOL = {
  name: "submit_questions",
  description: "Submit the finished batch of trivia questions. Call this exactly once, at the end.",
  strict: true,
  input_schema: {
    type: "object",
    properties: {
      questions: {
        type: "array",
        items: {
          type: "object",
          properties: {
            category: { type: "string", enum: CATEGORY_IDS },
            difficulty: { type: "integer", enum: [1, 2, 3] },
            question: { type: "string" },
            answer: { type: "string" },
            wrong_answers: { type: "array", items: { type: "string" } },
            note: { type: "string" },
          },
          required: ["category", "difficulty", "question", "answer", "wrong_answers", "note"],
          additionalProperties: false,
        },
      },
    },
    required: ["questions"],
    additionalProperties: false,
  },
};

async function fetchClaude(added, existingQuestions, perCategory = 3) {
  const { default: Anthropic } = await import("@anthropic-ai/sdk");
  const client = new Anthropic();
  const recent = existingQuestions.slice(-250).map((q) => "- " + q.q).join("\n");
  const prompt = `You write questions for a pub trivia practice app used by a group of friends.

Today is ${added}. Write ${perCategory} new multiple-choice questions for EACH of these categories: ${CATEGORY_IDS.join(", ")}
(pop = film & TV, geo = geography, sci = science & nature, random = fun general knowledge).

Lean toward things a quiz host might ask this month: recent film and TV releases, awards, chart news, sports results, anniversaries.
Use web search to confirm every fact about recent events. Leave out anything you can't confirm, or any claim likely to go out of date soon (such as "the current record holder").

Rules for each question:
- One unambiguous correct answer. Three plausible wrong answers of the same type (all cities, all years, and so on).
- Difficulty: 1 = most people know it, 2 = a regular quizzer knows it, 3 = a hard one.
- note: one short sentence of context that helps the fact stick, or "" if there's nothing useful to add.
- Don't repeat or closely paraphrase any of these existing questions:
${recent}

When you're finished, call submit_questions once with the whole batch.`;

  const messages = [{ role: "user", content: prompt }];
  for (let turn = 0; turn < 6; turn++) {
    const response = await client.beta.messages.create({
      model: "claude-opus-5-5",
      max_tokens: 16000,
      output_config: { effort: "high" },
      betas: ["server-side-fallback-2026-07-01"],
      fallbacks: "default",
      tools: [{ type: "web_search_20260209", name: "web_search", max_uses: 15 }, SUBMIT_TOOL],
      messages,
    });
    if (response.stop_reason === "refusal") throw new Error("Claude declined the request");
    const submit = response.content.find((b) => b.type === "tool_use" && b.name === "submit_questions");
    if (submit) {
      return submit.input.questions.map((x) => fromSubmitted(x, "claude", added));
    }
    messages.push({ role: "assistant", content: response.content });
    if (response.stop_reason !== "pause_turn") {
      messages.push({ role: "user", content: "Please call submit_questions with the batch now." });
    }
  }
  throw new Error("Claude never submitted a batch");
}

// ---------- main ----------
export function fromSubmitted(x, src, added) {
  return {
    id: idFor(String(x.question || "")),
    c: x.category,
    d: x.difficulty,
    q: String(x.question || "").trim(),
    a: String(x.answer || "").trim(),
    w: Array.isArray(x.wrong_answers) ? x.wrong_answers.map((w) => String(w).trim()) : [],
    n: String(x.note || "").trim(),
    src,
    added,
  };
}

async function main() {
  const argv = process.argv.slice(2);
  const args = new Set(argv);
  const importFile = args.has("--import") ? argv[argv.indexOf("--import") + 1] : null;
  const added = new Date().toISOString().slice(0, 10);
  const core = await loadWindowVar(CORE_FILE, "TRIVIA_QUESTIONS");
  if (!core) throw new Error("Couldn't read questions.js");
  const existing = (await loadWindowVar(PACK_FILE, "TRIVIA_PACKS"))?.questions || [];

  const candidates = [];
  if (importFile) {
    const list = JSON.parse(await readFile(importFile, "utf8"));
    if (!Array.isArray(list)) throw new Error("--import file must hold a JSON array");
    candidates.push(...list.map((x) => fromSubmitted(x, "claude", added)));
    console.log(`Import: read ${list.length}`);
  } else if (!args.has("--claude-only")) {
    const fromTdb = await fetchOpenTdb(added);
    console.log(`Open Trivia DB: fetched ${fromTdb.length}`);
    candidates.push(...fromTdb);
  }
  if (!importFile && (args.has("--claude") || args.has("--claude-only"))) {
    if (!process.env.ANTHROPIC_API_KEY) {
      console.warn("Skipping Claude: ANTHROPIC_API_KEY isn't set.");
    } else {
      const fromClaude = await fetchClaude(added, [...core, ...existing]);
      console.log(`Claude: wrote ${fromClaude.length}`);
      candidates.push(...fromClaude);
    }
  }

  const { pack, accepted, rejected } = mergeIntoPack(existing, candidates, core);
  for (const r of rejected.filter((r) => !r.problems.includes("duplicate"))) {
    console.warn(`Rejected: ${r.q} (${r.problems.join(", ")})`);
  }
  console.log(`Added ${accepted.length} new questions; pack now holds ${pack.length}.`);
  if (accepted.length) await writeFile(PACK_FILE, renderPackFile(pack, added));
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
